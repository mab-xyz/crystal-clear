#!/usr/bin/env python3
"""Compute confusion matrix metrics from tx-risk result JSON."""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Dict


def _classify(entry: Dict[str, object]) -> str:
    classification = str(entry.get("classification", "")).lower()
    if classification in {"skipped", "dry-run"}:
        return "skipped"

    status = str(entry.get("status", "")).upper()
    tx_type = str(entry.get("tx_type", "")).lower()
    is_attack = tx_type.startswith("attack")
    is_dangerous = status == "DANGEROUS"
    if is_attack and is_dangerous:
        return "tp"
    if is_attack and not is_dangerous:
        return "fn"
    if (not is_attack) and is_dangerous:
        return "fp"
    return "tn"


def compute(entries):
    raw = {}
    overall = defaultdict(int)
    for entry in entries:
        incident_id = entry.get("incident_id") or "unknown"
        info = raw.setdefault(
            incident_id,
            {
                "incident_name": entry.get("incident_name", ""),
                "attack": defaultdict(int),
                "normal": defaultdict(int),
            },
        )
        label = _classify(entry)
        if label == "skipped":
            overall[label] += 1
            continue
        overall[label] += 1
        tx_type = str(entry.get("tx_type", "")).lower()
        target = info["attack"] if tx_type.startswith("attack") else info["normal"]
        target[label] += 1

    per_incident = {}
    for incident_id, stats in raw.items():
        attack_counts = stats["attack"]
        normal_counts = stats["normal"]
        attack_label = "n/a"
        if attack_counts:
            attack_label = "tp" if attack_counts.get("tp", 0) else "fn"
        normal_label = "n/a"
        if normal_counts:
            normal_label = "fp" if normal_counts.get("fp", 0) else "tn"
        per_incident[incident_id] = {
            "attack": attack_label,
            "normal": normal_label,
        }

    return per_incident, dict(overall)


def parse_args(argv=None):
    parser = argparse.ArgumentParser(
        description="Compute confusion matrix counts from tx-risk results",
    )
    parser.add_argument(
        "--input",
        default="results/mab_tx_risk_results.json",
        help="Path to JSON generated by fetch_mab_tx_risk.py",
    )
    parser.add_argument(
        "--output",
        default="results/mab_tx_confusion_matrix.json",
        help="Path to write confusion matrix JSON",
    )
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    input_path = Path(args.input)
    if not input_path.exists():
        print(f"Input file not found: {input_path}", file=sys.stderr)
        return 2
    with input_path.open("r") as src:
        payload = json.load(src)
    entries = payload.get("results") if isinstance(payload, dict) else payload
    if not isinstance(entries, list):
        raise SystemExit("Input JSON must contain a list of results")
    per_incident, totals = compute(entries)
    out = {
        "input": str(input_path),
        "overall": totals,
        "by_incident": per_incident,
    }
    output_path = Path(args.output)
    if output_path.parent:
        output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w") as dest:
        json.dump(out, dest, indent=2)
    print(
        f"Wrote confusion matrix for {len(per_incident)} incidents to {output_path}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
